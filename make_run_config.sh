#!/bin/bash
# ==============================================================================
# make_run_config.sh -- generate a minimal config/runNN.conf
#
# Emits only the run identity (RUN_NUMBER / MDIDN / SETL / INSTRUMENT) and an
# empty DATE_RANGES. The dateranges are intentionally NOT written: genDRlist
# produces the authoritative runNN.dateranges.lst in Part 1/2, and the wrappers
# read it automatically when DATE_RANGES is empty. This keeps one source of
# truth for dateranges and matches run_lookup.sh's identity values.
#
# MDIDN uses the verified formula (== run_lookup.sh):
#   MDIDN = 6256 + RUN_NUMBER * 72
#   check: Run 1->6328, 74->11584, 79->11944, 80->12016, 81->12088
#
# Usage:
#   ./make_run_config.sh 81              # write config/run81.conf
#   ./make_run_config.sh 81 --dry-run    # print to stdout, write nothing
#   ./make_run_config.sh 81 --force      # overwrite an existing config
# ==============================================================================

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

RUN_NUMBER=""
DRY_RUN=false
FORCE=false
for arg in "$@"; do
    case "$arg" in
        --dry-run) DRY_RUN=true ;;
        --force)   FORCE=true ;;
        -h|--help)
            echo "Usage: $(basename "$0") NN [--dry-run] [--force]"
            exit 0 ;;
        ''|*[!0-9]*)
            echo "ERROR: run number must be a positive integer, got: $arg" >&2
            exit 1 ;;
        *) RUN_NUMBER="$arg" ;;
    esac
done

if [[ -z "$RUN_NUMBER" ]]; then
    echo "ERROR: run number required. Usage: $(basename "$0") NN [--dry-run] [--force]" >&2
    exit 1
fi

# Identity (self-contained; no external parse dependency)
MDIDN=$((6256 + RUN_NUMBER * 72))
SETL=24                          # 24 three-day sets per 72-day run (structural)
INSTRUMENT=hmi

OUT="${SCRIPT_DIR}/config/run${RUN_NUMBER}.conf"

read -r -d '' BODY <<EOF || true
# ==============================================================================
# Run ${RUN_NUMBER} Configuration - pipeline-v2  (generated by make_run_config.sh)
# ==============================================================================
# -- Run identification ------------------------------------------------------
RUN_NUMBER=${RUN_NUMBER}
MDIDN=${MDIDN}
SETL=${SETL}
INSTRUMENT=${INSTRUMENT}
# -- Date ranges -------------------------------------------------------------
# Left empty on purpose. genDRlist writes runNN.dateranges.lst in Part 1/2, and
# the wrappers read it automatically. Fill this only to override with a subset.
DATE_RANGES=()
# -- Tuning (optional) -------------------------------------------------------
# MAVG_TIMEOUT=1800
# PSDR_TIMEOUT=600
EOF

if [[ "$DRY_RUN" == "true" ]]; then
    echo "# [DRY-RUN] would write ${OUT}:"
    echo "$BODY"
    exit 0
fi

if [[ -e "$OUT" && "$FORCE" != "true" ]]; then
    echo "ERROR: ${OUT} already exists. Use --force to overwrite." >&2
    exit 1
fi

mkdir -p "${SCRIPT_DIR}/config"
printf '%s\n' "$BODY" > "$OUT"
echo "Wrote ${OUT}"
echo "  RUN_NUMBER=${RUN_NUMBER}  MDIDN=${MDIDN}  SETL=${SETL}  INSTRUMENT=${INSTRUMENT}"
echo "  DATE_RANGES left empty -> sourced from runNN.dateranges.lst at run time."
